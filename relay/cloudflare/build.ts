// Prepares what the Worker can't do at start: reading the protocol's files
// and compiling JSON Schema validators (Workers forbid code generation from
// strings). Writes gen/protocol-files.ts and gen/validators.js, which the
// aliases in wrangler.toml put in place of node:fs and Ajv for the Agent layer.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { Ajv2020 } from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";

// A CommonJS module: its function is on `.default`.
const standaloneCode = (standalone as unknown as { default: (ajv: Ajv2020, refs: Record<string, string>) => string }).default;

const protocol = new URL("../../protocol/", import.meta.url);
const gen = new URL("./gen/", import.meta.url);
mkdirSync(gen, { recursive: true });

// Every file the Agent layer reads (agent/src/protocol.ts, capabilities/bundle.ts).
const files: Record<string, string> = {};
for (const dir of ["schema", "tool-text", "generated/tools"])
  for (const f of readdirSync(new URL(dir + "/", protocol))) files[`${dir}/${f}`] = readFileSync(new URL(`${dir}/${f}`, protocol), "utf8");
writeFileSync(new URL("protocol-files.ts", gen), `// Generated by build.ts from protocol/. Do not edit.\nexport default ${JSON.stringify(files)} as Record<string, string>;\n`);

// The same Ajv the Agent layer makes, with every validator it asks for.
const BASE = "https://reflex.eilmer.si/protocol/v1/";
const ajv = new Ajv2020({ strict: true, allErrors: true, allowUnionTypes: true, code: { source: true, esm: true } });
const ids: string[] = [];
for (const [path, text] of Object.entries(files)) {
  if (!path.startsWith("schema/") || !path.endsWith(".schema.json")) continue;
  const s = JSON.parse(text);
  ajv.addSchema(s);
  ids.push(s.$id);
}
const exportsMap: Record<string, string> = {};
const byId: Record<string, string> = {};
const byCompile: Record<string, string> = {};
ids.forEach((id, i) => {
  exportsMap[`s${i}`] = id;
  byId[id] = `s${i}`;
});
// agent/src/protocol.ts compiles each apply op variant as { $ref: ".../oneOf/<n>" }.
const apply = JSON.parse(files["schema/apply.input.schema.json"]);
apply.properties.ops.items.oneOf.forEach((_: unknown, i: number) => {
  const schema = { $ref: `${BASE}apply.input.schema.json#/properties/ops/items/oneOf/${i}` };
  const id = `urn:reflex:apply-variant:${i}`;
  ajv.addSchema({ $id: id, ...schema });
  exportsMap[`v${i}`] = id;
  byCompile[JSON.stringify(schema)] = `v${i}`;
});
writeFileSync(new URL("validators.js", gen), `// Generated by build.ts. Do not edit.\n${standaloneCode(ajv, exportsMap)}\nexport const byId = ${JSON.stringify(byId)};\nexport const byCompile = ${JSON.stringify(byCompile)};\n`);
console.log(`build: ${Object.keys(files).length} protocol files, ${Object.keys(exportsMap).length} validators`);
